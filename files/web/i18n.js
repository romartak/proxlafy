window.pickLang = function () {
  var saved = null;
  try { saved = localStorage.getItem("proxlafy_lang"); } catch (e) {}
  if (saved === "en" || saved === "es") return saved;
  return (navigator.language || "es").toLowerCase().indexOf("es") === 0 ? "es" : "en";
};
